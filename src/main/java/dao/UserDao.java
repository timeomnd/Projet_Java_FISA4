package dao;

import org.mindrot.jbcrypt.BCrypt;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;


public class UserDao {

    public boolean registerUser(String firstName, String lastName, String email, String username, String password) {
        // Query to insert personal data into the registration_form table
        String insertFormQuery = "INSERT INTO registration_form (first_name, last_name, email) VALUES (?, ?, ?)";

        // Query to insert personal data into authentification table
        String insertAuthQuery = "INSERT INTO authentication (id_registration_form, username, password_hash) VALUES (?, ?, ?)";

        try (Connection conn = DatabaseManager.getConnection()) {

            //Insert into registration_form and request the generated ID
            try (PreparedStatement formStmt = conn.prepareStatement(insertFormQuery, Statement.RETURN_GENERATED_KEYS)) {
                formStmt.setString(1, firstName);
                formStmt.setString(2, lastName);
                formStmt.setString(3, email);
                formStmt.executeUpdate();

                // Retrieve the new ID generated by the database
                try (ResultSet generatedKeys = formStmt.getGeneratedKeys()) {
                    if (generatedKeys.next()) {
                        int registrationId = generatedKeys.getInt(1);

                        // Insert into authentication using the newly created ID
                        try (PreparedStatement authStmt = conn.prepareStatement(insertAuthQuery)) {
                            authStmt.setInt(1, registrationId);
                            authStmt.setString(2, username);

                            //hash the password using BCrypt lib
                            String hashPassword = BCrypt.hashpw(password,BCrypt.gensalt());
                            authStmt.setString(3, hashPassword);

                            authStmt.executeUpdate();

                            System.out.println("User successfully registered!");
                            return true;
                        }
                    }
                }
            }
        } catch (SQLException e) {
            System.out.println("Error during user registration: " + e.getMessage());
        }
        return false;
    }

    public int loginUser(String userName, String password){
        String loginQuery = "Select id, password_hash from authentification where username = ?";
        try(Connection connection = DatabaseManager.getConnection();
            PreparedStatement statement = connection.prepareStatement(loginQuery)){
            statement.setString(1, userName);
            try(ResultSet result = statement.executeQuery()) {
                if(result.next()){
                    int authId = result.getInt("id");
                    String storedHashPassword = result.getString("password_hash");
                    if (BCrypt.checkpw(password, storedHashPassword)) { //check if the login password is the same as the bdd password
                        System.out.println("Login successful! Welcome back, " + userName + ".");
                        return authId; // Return the user's ID for the active session
                    } else {
                        System.out.println("Login failed: Incorrect password.");
                    }
                } else {
                    System.out.println("Login failed: Username not found.");
                }
            }
        } catch (SQLException e) {
            System.out.println("Error during login process: " + e.getMessage());
        }
        // Return -1 if the login fails
        return -1;
    }
}